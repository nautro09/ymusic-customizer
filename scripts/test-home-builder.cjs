const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require('playwright');

async function check(browser, platform) {
  const page = await browser.newPage({ viewport: { width: 1200, height: 820 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve(__dirname, '..', platform, 'demo.html')).href);
  const mountHero = () => page.evaluate(() => {
    const hero = document.createElement('section');
    hero.dataset.testId = 'VIBE_PAGE';
    hero.style.cssText = 'position:fixed;inset:40px 15px 110px 120px;container-type:size;background:#181c24';
    hero.innerHTML = '<div data-test-id="VIBE_DYNAMIC_ARTISTS" style="position:absolute;top:100px;left:10%;font-size:32px">Исполнитель</div>' +
      '<button data-test-id="VIBE_PLAYERBAR_TIMECODE_SLIDER" style="position:absolute;bottom:20%;left:30%;width:180px;height:48px">Трек</button>';
    hero.querySelector('button').onclick = () => { window.sliderClicked = true; };
    document.body.append(hero);
    YMusicCustomizer.update({ waveClock:'date', clockStyle:'orbit' });
  });
  await page.waitForFunction(() => window.YMusicCustomizer);
  await mountHero();
  const ui = page.locator('#ymusic-customizer-root');
  const find = id => ui.locator('#ymc-' + id);
  await page.evaluate(() => YMusicCustomizer.open());
  await ui.locator('[data-tab="layout"]').click();
  await find('home-builder').locator('.section-toggle').click();
  await find('builder-open').click();
  const frame = find('builder-frame');
  const block = page.locator('[data-test-id="VIBE_PLAYERBAR_TIMECODE_SLIDER"]');
  const waitPaint = () => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await find('builder-block').selectOption('timeline');
  await waitPaint();
  const initial = await block.boundingBox();
  const rect = await frame.boundingBox();
  await page.mouse.move(rect.x + 8, rect.y + 8);
  await page.mouse.down();
  await page.mouse.move(rect.x + 98, rect.y - 42, { steps:4 });
  await page.mouse.up();
  await waitPaint();
  const moved = await block.boundingBox();
  assert.ok(Math.abs(moved.x-initial.x-90) < 2 && Math.abs(moved.y-initial.y+50) < 2, JSON.stringify({initial,moved}));
  await find('builder-size').fill('135');
  await waitPaint();
  assert.ok(Math.abs((await block.boundingBox()).width - initial.width*1.35) < 1);
  await find('builder-undo').click();
  await waitPaint();
  assert.ok(Math.abs((await block.boundingBox()).width-initial.width)<1);
  await find('builder-redo').click();
  await waitPaint();
  assert.ok(Math.abs((await block.boundingBox()).width-initial.width*1.35)<1);
  await find('builder-save').click();
  await find('close').click();
  await block.click();
  assert.equal(await page.evaluate(() => window.sliderClicked), true);
  const saved = await page.evaluate(() => YMusicCustomizer.getTheme().homeLayout);
  assert.equal(JSON.parse(saved).timeline[2], 135);
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('ymc:theme:v2') || '{}').homeLayout ||
    Object.keys(localStorage).some(key => localStorage.getItem(key).includes('"homeLayout":"{')));
  await page.reload();
  await mountHero();
  await waitPaint();
  assert.equal(await page.evaluate(() => YMusicCustomizer.getTheme().homeLayout), saved);
  assert.ok(Math.abs((await block.boundingBox()).width - initial.width*1.35) < 1);
  await page.setViewportSize({ width:840, height:650 });
  await waitPaint();
  const field = await page.locator('[data-test-id="VIBE_PAGE"]').boundingBox();
  const smaller = await block.boundingBox();
  const [relative] = JSON.parse(saved).timeline;
  assert.ok(Math.abs(smaller.x+smaller.width/2-field.x-field.width*relative/1000) < 2);
  await page.evaluate(() => YMusicCustomizer.open());
  await ui.locator('[data-tab="layout"]').click();
  if (await find('home-builder').locator('.section-toggle').getAttribute('aria-expanded') === 'false') {
    await find('home-builder').locator('.section-toggle').click();
  }
  await find('builder-open').click();
  await find('builder-reset').click();
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => YMusicCustomizer.getTheme().homeLayout), saved);
  await find('builder-open').click();
  await find('builder-reset').click();
  await find('builder-save').click();
  assert.equal(await page.evaluate(() => YMusicCustomizer.getTheme().homeLayout), '');
  assert.equal((await block.boundingBox()).width, initial.width);
  // Exercise the new controls against native buttons and a full-width artist wrapper.
  await page.setViewportSize({width:1200,height:820});
  await find('builder-open').click();
  await page.evaluate(() => {
    const hero = document.querySelector('[data-test-id=VIBE_PAGE]');
    const title = hero.querySelector('[data-test-id=VIBE_DYNAMIC_ARTISTS]');
    title.style.width = '100%';
    title.innerHTML = '<div><a href="#artist">Исполнитель</a></div>';
    const cover = document.createElement('div');
    cover.dataset.testId = 'VIBE_PLAYERBAR_ALBUM_COVER';
    cover.style.cssText = 'position:absolute;left:15%;top:38%;width:64px;height:64px;background:teal';
    hero.append(cover);
    const controls = document.createElement('div');
    controls.className = 'VibePlayerControls_root__test';
    controls.style.cssText = 'position:absolute;left:15%;top:68%;display:flex;gap:10px';
    controls.innerHTML = '<button data-test-id="PLAY_BUTTON">Пуск</button><button data-test-id="NEXT_TRACK_BUTTON">Дальше</button>';
    controls.onclick = () => { window.nativePresses = (window.nativePresses || 0) + 1; };
    hero.append(controls);
  });
  const visible = key => find('builder-cards').locator('[data-block="'+key+'"] input');
  const pick = async key => { await find('builder-block').selectOption(key); await waitPaint(); };
  await pick('title');
  const titleBox = await frame.boundingBox();
  assert.ok(titleBox.width < 265 && titleBox.width > 70, JSON.stringify(titleBox));
  const next = page.locator('[data-test-id=VIBE_PAGE] [data-test-id=NEXT_TRACK_BUTTON]');
  const center = async locator => {
    const b = await locator.boundingBox();
    return { x:b.x+b.width/2, y:b.y+b.height/2 };
  };
  const nextPos = await center(next);
  await page.mouse.click(nextPos.x,nextPos.y);
  assert.equal(await page.evaluate(() => window.nativePresses || 0),0);
  assert.equal(await find('builder-block').inputValue(),'next');
  await visible('next').uncheck();
  assert.equal(await next.isVisible(),false);
  assert.equal(await ui.locator('[data-prop=hideVibeNext]').isChecked(),true);
  assert.equal(await page.locator('[data-test-id=VIBE_PAGE] [data-test-id=PLAY_BUTTON]').isVisible(),true);
  await visible('next').check();
  await pick('coverSolo');
  await find('builder-width').fill('155');
  await find('builder-height').fill('75');
  await waitPaint();
  const art = page.locator('[data-test-id=VIBE_PLAYERBAR_ALBUM_COVER]');
  assert.ok(Math.abs((await art.boundingBox()).width-99.2)<1);
  assert.ok(Math.abs((await art.boundingBox()).height-48)<1);
  await page.evaluate(async () => {
    const portrait = document.createElement('div');
    portrait.dataset.testId = 'VIBE_ARTIST_COVER';
    portrait.style.cssText = 'position:absolute;left:10px;bottom:10px';
    const image = new Image(24,24);
    image.src = document.createElement('canvas').toDataURL();
    await image.decode(); portrait.append(image);
    document.querySelector('[data-test-id=VIBE_PAGE]').append(portrait);
  });
  await page.waitForFunction(() => Math.abs(document.querySelector('[data-test-id=VIBE_PLAYERBAR_ALBUM_COVER]').getBoundingClientRect().width-64)<1);
  await pick('coverArtist');
  await find('builder-size').fill('80');
  await waitPaint();
  await visible('clock').uncheck();
  const target = await center(block);
  const card = find('builder-cards').locator('[data-block=clock]');
  const screen = await find('builder-area').boundingBox();
  await card.dragTo(find('builder-area'),{targetPosition:{x:target.x-screen.x,y:target.y-screen.y}});
  await page.waitForFunction(() => document.querySelector('[data-ymc-wave-clock]'));
  assert.equal(await visible('clock').isChecked(),true);
  await waitPaint();
  assert.match(await find('builder-warning').textContent(), /Строка трека/);
  await find('builder-save').click();
  const committed = await page.evaluate(() => YMusicCustomizer.getTheme());
  const positions = JSON.parse(committed.homeLayout);
  assert.deepEqual(positions.coverSolo.slice(2),[155,75]);
  assert.deepEqual(positions.coverArtist.slice(2),[80]);
  assert.equal(committed.waveClock,'date');
  await find('builder-open').click();
  await visible('clock').uncheck();
  await find('builder-cancel').click();
  assert.equal(await page.evaluate(() => YMusicCustomizer.getTheme().waveClock),'date');
  assert.deepEqual(errors, []);
  console.log('PASS', platform, 'home layout drag, resize, save, reload, responsive geometry, native click, cancel and reset');
  await page.close();
}

(async () => {
  const browser = await chromium.launch({ executablePath: process.env.YMC_CHROMIUM || undefined });
  try {
    for (const platform of ['macos', 'windows']) await check(browser, platform);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
